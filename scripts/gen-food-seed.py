#!/usr/bin/env python3
"""Generate R__food_catalog.sql from db/catalog/foods.csv (BR-CAT-01).

Usage:  python scripts/gen-food-seed.py [--check]
  --check  exit 1 if the committed SQL is out of date (used in CI)

The output is a Flyway *repeatable* migration: it re-runs whenever its content changes and
upserts every catalog food by name, so editing the CSV and regenerating is the whole workflow.
Foods without a source (legacy rows seeded before the catalog) are deactivated, never deleted,
so historical plans keep working (BR-CAT-04).
"""
import csv
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "backend/src/main/resources/db/catalog/foods.csv"
SQL_PATH = ROOT / "backend/src/main/resources/db/migration/R__food_catalog.sql"

ROLES = {"PROTEIN", "CARB", "PRODUCE", "FAT"}
STATES = {"RAW", "COOKED", "DRY"}
ALLERGENS = {"GLUTEN", "CRUSTACEANS", "EGGS", "FISH", "PEANUTS", "SOY", "MILK", "TREE_NUTS",
             "CELERY", "MUSTARD", "SESAME", "SULPHITES", "LUPIN", "MOLLUSCS"}
FLAGS = {"VEGAN", "VEGETARIAN", "HALAL", "KOSHER"}
SLOT_CODES = {"B": ["BREAKFAST"], "S": ["MORNING_SNACK", "AFTERNOON_SNACK"],
              "L": ["LUNCH"], "D": ["DINNER"]}
NUMERIC = ["kcal", "protein_g", "carbs_g", "fat_g", "sugar_g", "fiber_g", "sodium_mg",
           "portion_min_g", "portion_max_g", "portion_step_g", "portion_default_g"]


def split(value):
    return [v for v in value.split("|") if v] if value else []


def is_multiple(value, step):
    q = value / step
    return abs(q - round(q)) < 1e-6


def validate(row, line):
    errors = []
    n = {k: float(row[k]) for k in NUMERIC}
    if row["role"] not in ROLES:
        errors.append(f"role {row['role']!r}")
    if row["state"] not in STATES:
        errors.append(f"state {row['state']!r}")
    errors += [f"allergen {a!r}" for a in split(row["allergens"]) if a not in ALLERGENS]
    errors += [f"flag {f!r}" for f in split(row["diet_flags"]) if f not in FLAGS]
    errors += [f"slot {s!r}" for s in split(row["slots"]) if s not in SLOT_CODES]
    if not split(row["slots"]):
        errors.append("no slots")
    if row["meat"] not in ("true", "false"):
        errors.append("meat must be true/false")
    if not row["source"]:
        errors.append("missing source")
    if "VEGAN" in split(row["diet_flags"]) and "VEGETARIAN" not in split(row["diet_flags"]):
        errors.append("VEGAN implies VEGETARIAN")
    # BR-CAT-02
    if any(n[k] < 0 for k in NUMERIC):
        errors.append("negative value")
    if n["fiber_g"] > n["carbs_g"] or n["sugar_g"] > n["carbs_g"]:
        errors.append("fiber and sugar must not exceed carbs")
    if n["protein_g"] + n["carbs_g"] + n["fat_g"] > 100:
        errors.append("macros exceed 100 g")
    expected = (4 * n["protein_g"] + 4 * (n["carbs_g"] - n["fiber_g"]) + 2 * n["fiber_g"]
                + 9 * n["fat_g"])
    if abs(n["kcal"] - expected) > max(0.15 * n["kcal"], 10):
        errors.append(f"energy {n['kcal']} vs macros {expected:.1f} (BR-CAT-02)")
    # BR-CMP-03
    step = n["portion_step_g"]
    if not (0 < n["portion_min_g"] <= n["portion_default_g"] <= n["portion_max_g"]):
        errors.append("portion bounds")
    if not all(is_multiple(n[k], step) for k in ("portion_min_g", "portion_max_g", "portion_default_g")):
        errors.append("portions must be multiples of the step")
    if errors:
        raise SystemExit(f"foods.csv line {line} ({row['name']}): " + "; ".join(errors))


def q(text):
    return "'" + text.replace("'", "''") + "'"


def load_rows():
    lines = [l for l in CSV_PATH.read_text(encoding="utf-8").splitlines() if l and not l.startswith("#")]
    rows = list(csv.DictReader(io.StringIO("\n".join(lines))))
    names = set()
    for i, row in enumerate(rows, start=2):
        validate(row, i)
        if row["name"].lower() in names:
            raise SystemExit(f"duplicate name {row['name']!r}")
        names.add(row["name"].lower())
    return rows


def render(rows):
    out = [
        "-- GENERATED by scripts/gen-food-seed.py from db/catalog/foods.csv. Do not edit by hand.",
        "-- Repeatable migration: upserts the curated catalog by name (BR-CAT-01).",
        "",
    ]
    for row in rows:
        name = q(row["name"])
        food_id = f"(select id from food_items where name = {name})"
        out.append(f"-- {row['name']}")
        out.append(
            "insert into food_items (name, category, role, state, calories_per100g, protein_per100g, "
            "carbs_per100g, fat_per100g, sugar_per100g, fiber_per100g, sodium_mg_per100g, "
            "portion_min_g, portion_max_g, portion_step_g, default_portion_g, source, active, "
            "allergens_known, meat)\n"
            f"values ({name}, {q(row['category'])}, {q(row['role'])}, {q(row['state'])}, "
            f"{row['kcal']}, {row['protein_g']}, {row['carbs_g']}, {row['fat_g']}, {row['sugar_g']}, "
            f"{row['fiber_g']}, {row['sodium_mg']}, {row['portion_min_g']}, {row['portion_max_g']}, "
            f"{row['portion_step_g']}, {row['portion_default_g']}, {q(row['source'])}, true, true, "
            f"{row['meat']})\n"
            "on conflict (name) do update set category = excluded.category, role = excluded.role, "
            "state = excluded.state, calories_per100g = excluded.calories_per100g, "
            "protein_per100g = excluded.protein_per100g, carbs_per100g = excluded.carbs_per100g, "
            "fat_per100g = excluded.fat_per100g, sugar_per100g = excluded.sugar_per100g, "
            "fiber_per100g = excluded.fiber_per100g, sodium_mg_per100g = excluded.sodium_mg_per100g, "
            "portion_min_g = excluded.portion_min_g, portion_max_g = excluded.portion_max_g, "
            "portion_step_g = excluded.portion_step_g, default_portion_g = excluded.default_portion_g, "
            "source = excluded.source, active = true, allergens_known = true, meat = excluded.meat;"
        )
        out.append(f"delete from food_allergens where food_id = {food_id};")
        out.append(f"delete from food_diet_flags where food_id = {food_id};")
        out.append(f"delete from food_suitable_slots where food_id = {food_id};")
        for a in split(row["allergens"]):
            out.append(f"insert into food_allergens (food_id, allergen) values ({food_id}, {q(a)});")
        for f in split(row["diet_flags"]):
            out.append(f"insert into food_diet_flags (food_id, diet_flag) values ({food_id}, {q(f)});")
        slots = sorted({s for code in split(row["slots"]) for s in SLOT_CODES[code]})
        for s in slots:
            out.append(f"insert into food_suitable_slots (food_id, slot) values ({food_id}, {q(s)});")
        out.append("")
    out.append("-- Legacy rows (no source) stay inactive: kept for history, never offered (BR-CAT-04)")
    out.append("update food_items set active = false where source is null;")
    return "\n".join(out) + "\n"


def main():
    sql = render(load_rows())
    if "--check" in sys.argv:
        current = SQL_PATH.read_text(encoding="utf-8") if SQL_PATH.exists() else ""
        if current.replace("\r\n", "\n") != sql:
            raise SystemExit("R__food_catalog.sql is out of date: run python scripts/gen-food-seed.py")
        print("R__food_catalog.sql is up to date")
        return
    SQL_PATH.write_text(sql, encoding="utf-8", newline="\n")
    print(f"wrote {SQL_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
